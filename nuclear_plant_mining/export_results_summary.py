import os
from datetime import datetime
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages


def add_image_page(pdf: PdfPages, image_path: str, title: str, caption: str):
    fig = plt.figure(figsize=(11.69, 8.27))  # A4 landscape in inches (approx)
    fig.suptitle(title, fontsize=14, y=0.98)
    try:
        img = plt.imread(image_path)
        ax = fig.add_axes([0.05, 0.15, 0.9, 0.78])
        ax.imshow(img)
        ax.axis('off')
        fig.text(0.05, 0.06, caption + f"\nFile: {os.path.relpath(image_path)}", fontsize=9, va='top')
    except Exception as e:
        fig.text(0.05, 0.5, f"Unable to load image: {image_path}\nError: {e}", fontsize=12)
    pdf.savefig(fig, dpi=200, bbox_inches='tight')
    plt.close(fig)


def main():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    results_dir = os.path.join(base_dir, 'data', 'mining_results')
    processed_dir = os.path.join(base_dir, 'data', 'processed')
    out_pdf = os.path.join(results_dir, 'Results_Summary.pdf')

    items = [
        (os.path.join(results_dir, 'eda_comprehensive.png'),
         'Exploratory Data Analysis',
         'Six-panel overview including correlation heatmap, risk distribution, sump flow by risk, radiation timeline with leak markers, distributions, and PCA scatter.'),
        (os.path.join(processed_dir, 'processing_overview.png'),
         'Processing Overview',
         'Denoising comparison, PCA scatter (sample), and missingness heatmap summarizing preprocessing effects.'),
        (os.path.join(results_dir, 'confusion_matrix_random_forest.png'),
         'Multi-class Classification: Confusion Matrix (Random Forest)',
         'Perfect diagonal confirms near-perfect risk-level prediction on synthetic data.'),
        (os.path.join(results_dir, 'feature_importance.png'),
         'Feature Importance (Random Forest)',
         'Radiation-related sensors and sump/flow dominate predictive power.'),
        (os.path.join(results_dir, 'regression_scatter.png'),
         'Regression: Actual vs Predicted Leak Rate (Random Forest)',
         'Tight alignment with the identity line; R²≈0.997 and RMSE≈1.06 LPM.'),
        (os.path.join(results_dir, 'model_comparison_summary.png'),
         'Model Comparison Summary',
         'Classification and regression comparisons, daily risk distribution, and correlation with leak events.'),
        (os.path.join(results_dir, 'roc_visualization_random_forest.png'),
         'Binary Classification ROC (Random Forest)',
         'ROC curve showing AUC≈1.00 for leak vs no-leak.'),
        (os.path.join(results_dir, 'dimensionality_reduction.png'),
         'Dimensionality Reduction (PCA)',
         'PC1–PC2 scatter by risk, explained variance, loadings, and PC1 over time.')
    ]

    with PdfPages(out_pdf) as pdf:
        # Cover page
        cover = plt.figure(figsize=(11.69, 8.27))
        cover.suptitle('Nuclear Plant Leak Detection — Results Summary', fontsize=16, y=0.9)
        txt = (
            'This PDF collects the key result figures generated by the pipeline without moving any files.\n'
            'Each page embeds an existing image from the data/mining_results or data/processed directory,\n'
            'with a short caption summarizing the insight.'
        )
        cover.text(0.06, 0.7, txt, fontsize=12)
        cover.text(0.06, 0.12, f'Generated: {datetime.now():%Y-%m-%d %H:%M:%S}', fontsize=10)
        pdf.savefig(cover, dpi=200, bbox_inches='tight')
        plt.close(cover)

        for path, title, caption in items:
            add_image_page(pdf, path, title, caption)

    print(f"Results summary PDF written to: {out_pdf}")


if __name__ == '__main__':
    main()




